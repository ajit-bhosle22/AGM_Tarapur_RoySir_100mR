void check_sw5_status(void)
{
	static uint32_t last_sw5_tick = 0;
	uint32_t now = HAL_GetTick();
	if (HAL_GPIO_ReadPin(GPIOA,GPIO_PIN_5) == GPIO_PIN_SET &&
			(now - last_sw5_tick > 300)) {
		last_sw5_tick = now;
		sw5_press_flag = true;
	}
}

