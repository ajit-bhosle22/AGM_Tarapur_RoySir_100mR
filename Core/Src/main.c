/**
 * @brief  The application entry point.
 * @retval int
 */
int main(void)
{

	/* USER CODE BEGIN 1 */

	/* USER CODE END 1 */

	/* MPU Configuration--------------------------------------------------------*/
	MPU_Config();

	/* MCU Configuration--------------------------------------------------------*/

	/* Reset of all peripherals, Initializes the Flash interface and the Systick. */
	HAL_Init();

	/* USER CODE BEGIN Init */

	/* USER CODE END Init */

	/* Configure the system clock */
	SystemClock_Config();

	/* Configure the peripherals common clocks */
	PeriphCommonClock_Config();

	/* USER CODE BEGIN SysInit */

	/* USER CODE END SysInit */

	/* Initialize all configured peripherals */
	MX_GPIO_Init();
	MX_DMA_Init();
	MX_UART8_Init();
	MX_USART2_UART_Init();
	MX_I2C4_Init();
	MX_SPI3_Init();
	MX_SPI4_Init();
	MX_TIM3_Init();
	MX_TIM4_Init();
	MX_DAC1_Init();
	MX_RTC_Init();
	MX_UART7_Init();
	MX_SPI1_Init();
	MX_FATFS_Init();
	/* USER CODE BEGIN 2 */

	g_sd_present = create_file();

	if(g_sd_present)
	{
		create_file();
		HAL_Delay(1);
		Logger_LoadIndex();
		open_files();
	}

	// ----------------EEPROM Waiting Time-----------------------
	HAL_Delay(500);

	// ------------------Read Saved Data--------------------------
	if(EEPROM_Read_Config(&hi2c4, EEPROM_ADDR, &g_config) != HAL_OK)
	{
		printf("I2c Read Failed\r\n");
	}

	if(g_config.MAGIC_NUMBER != 0xAA55)
	{
		Load_Default_Config(&g_config);
	}

	config_modbus_registers();
	config_variables();

	// -----------------Initialize 7_Segment-------------------------------
	MAX7219_Init();
	HAL_Delay(100);

	// ---------------Reconfigure (PC UART) With Saved Baud Rate------------
	PC_UART_ReInit(pending_new_baud);

	W5500_SPI = hspi3;
	LOG_UART  = huart7;

	// ------------------Initialize W5500 Eth Module----------------------
	if(W5500_init()!=0){
		Error_Handler();
	}

	// -----------------Opens socket and listens---------------------------
	modbus_tcp_server_init();

	lcd_init();
	HAL_Delay(2);

	load_all_factors();

	// ------------ Arm DMA USART2 (DTC) to catch frame ------------------------
	USART2_Start_RX(&huart2);

	HAL_RTCEx_DeactivateWakeUpTimer(&hrtc);

	HAL_RTCEx_SetWakeUpTimer_IT(
			&hrtc,
			0,
			RTC_WAKEUPCLOCK_CK_SPRE_16BITS
	);

	__HAL_TIM_SET_COUNTER(&htim4, 0);
	__HAL_TIM_CLEAR_FLAG(&htim4, TIM_FLAG_UPDATE);
	HAL_TIM_Base_Start_IT(&htim4);

	HAL_DAC_Start(&hdac1, DAC_CHANNEL_1);

	if(HAL_RTCEx_BKUPRead(&hrtc, RTC_BKP_DR0) != RTC_MAGIC_VALUE)
	{
		RTC_SetDefaultTimeDate();

		HAL_RTCEx_BKUPWrite(&hrtc,
				RTC_BKP_DR0,
				RTC_MAGIC_VALUE);
	}

	//-------------Configure Device In Normal State------------------------
	Handle_NormalState();
	Modbus_Registers.Reset        = 1;
	Modbus_Registers_PC_TCP.Reset = 1;

	HAL_SPI_DeInit(&hspi1);
	hspi1.Init.BaudRatePrescaler = SPI_BAUDRATEPRESCALER_8;
	HAL_SPI_Init(&hspi1);

	// ----- Capture Pulses--------
	HAL_TIM_IC_Start_IT(&htim3, TIM_CHANNEL_4);

	// -------TCP KEEP ALIVE TIMEOUT (5 sec)------------------
	setRTR(2000);
	setRCR(3);

	/* USER CODE END 2 */

	/* Infinite loop */
	/* USER CODE BEGIN WHILE */
	while (1)
	{
		/* USER CODE END WHILE */

		/* USER CODE BEGIN 3 */

		if(read_sd_flag)
		{
			sd_task();
		}
		else{
			modbus_task_dtc();
			modbus_task_pc();
			system_lcd_screen();
			e4_20mA_task();
			tcp_task();
			monitor_panel_unit_leds();
			update_rtc_registers();
			if(g_sd_present){
				sd_card_operations();
			}
			Check_Fault_Conditions();
			check_sw5_status();
		}
	}
	/* USER CODE END 3 */
}

